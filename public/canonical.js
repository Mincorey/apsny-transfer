// Подстановка канонического адреса при первой загрузке страницы.
//
// Раньше этот код жил инлайном прямо в index.html. Вынесен в отдельный файл
// сознательно: инлайновый <script> вынуждает держать в CSP директиву
// script-src 'unsafe-inline', а она разрешает выполнение ЛЮБОГО скрипта,
// который злоумышленник сумеет протащить в разметку — то есть сводит защиту
// от XSS практически к нулю. Внешний файл грузится с 'self' и позволяет
// оставить script-src строгим (см. vercel.json).
//
// Почему адрес вычисляется, а не зашит строкой — подробное объяснение
// в комментарии рядом с <link rel="canonical"> в index.html.
//
// Дальнейшие переходы внутри приложения обрабатывает компонент Canonical
// в src/App.tsx.
(function () {
  var path = location.pathname.replace(/\/+$/, '') || '/';
  var link = document.querySelector('link[rel="canonical"]');
  if (link) link.setAttribute('href', location.origin + path);
})();
