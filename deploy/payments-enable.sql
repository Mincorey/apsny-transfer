-- НЕ ПРИМЕНЯТЬ ЗАРАНЕЕ. Выполняется ровно в тот момент, когда включаются
-- платежи — тем же действием, что и переключение PAYMENTS_ENABLED.
--
-- ЗАЧЕМ. Функция publish_ride_free публикует поездку без оплаты и доступна
-- любому авторизованному пользователю. Пока публикация и так бесплатная, это
-- безобидно и именно так и задумано. В день, когда за публикацию начнут брать
-- деньги, это становится дырой: достаточно вызвать
--     POST /rest/v1/rpc/publish_ride_free {"p_ride_id": "..."}
-- напрямую из консоли браузера — и поездка опубликована мимо кассы. Никакой
-- ошибки при этом не возникнет, платёж просто не понадобится.
--
-- Линтер Supabase этого не показывает: с его точки зрения функция и должна
-- быть доступна авторизованным. Проблема не в правах, а в том, что смысл
-- функции меняется в момент включения оплаты.
--
-- ПОРЯДОК ДЕЙСТВИЙ В ДЕНЬ ВКЛЮЧЕНИЯ:
--   1. Подключить ЮMoney, проверить вебхук на реальном платеже.
--   2. Выполнить этот файл.
--   3. Переключить PAYMENTS_ENABLED в коде и убрать пометки «сейчас бесплатно».
--   4. Пройти раздел C в ПРОВЕРИТЬ.md — он проверяется только живыми деньгами.
--
-- Шаги 2 и 3 делаются вместе. Если выполнить только этот файл, публикация
-- сломается у всех: код ещё зовёт publish_ride_free, а права уже отобраны.

revoke execute on function public.publish_ride_free(uuid) from authenticated, anon;

-- Проверка: должно остаться только postgres и service_role.
select p.proname, array_to_string(p.proacl, ' | ') as права
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'public' and p.proname = 'publish_ride_free';
