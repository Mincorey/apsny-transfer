// src/lib/publishRide.ts
// Публикация поездки.
//
// Платная механика проекта: размещение объявления стоит 100 ₽, приём платежей —
// ЮMoney. Пока платёжная система подключается и проходит модерацию, публикация
// ВРЕМЕННО БЕСПЛАТНА: черновик (draft) публикуется через RPC publish_ride_free
// (draft → active), деньги не участвуют.
//
// Важно: интерфейс об этом говорит прямо. Кнопки ведут на страницу /payment,
// где показан тариф, способ оплаты и честная пометка о том, что сейчас
// публикация бесплатна. Сообщений вида «Оплата получена» при бесплатной
// публикации быть не должно — это недостоверные сведения об услуге.
//
// Когда ЮMoney будет подключена, здесь появится инициация платежа
// (start_ride_payment → форма quickpay), а публикация вернётся на серверное
// подтверждение через вебхук. Одновременно нужно будет отозвать право вызова
// publish_ride_free у обычных пользователей — см. пункт 8.8 аудита.

import { supabase } from './supabase';

/** Стоимость размещения объявления, ₽. */
export const PUBLICATION_PRICE = 100;

/** Название платёжной системы для отображения в интерфейсе и документах. */
export const PAYMENT_PROVIDER = 'ЮMoney';

/** Приём платежей ещё не подключён — публикация временно бесплатна. */
export const PAYMENTS_ENABLED = false;

/**
 * Публикует поездку-черновик (draft → active) и запускает аукцион.
 * Пока платёжная система не подключена — бесплатно.
 * Бросает ошибку, если RPC вернул ошибку.
 * @param rideId id поездки-черновика, принадлежащей текущему пользователю
 */
export async function publishRideFree(rideId: string): Promise<void> {
  const { error } = await supabase.rpc('publish_ride_free', { p_ride_id: rideId });
  if (error) throw error;
}
