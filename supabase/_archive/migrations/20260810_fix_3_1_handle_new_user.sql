-- ============================================================
-- 20260810_fix_3_1_handle_new_user.sql
--
-- Закрывает пункт 3.1 аудита AUDIT_2026-08-10.md:
-- «Регистрация может завершиться без профиля».
--
-- ПРОБЛЕМА
-- --------
-- Триггер handle_new_user создаёт запись в public.users при появлении
-- пользователя в auth.users. Вставка была обёрнута в блок
--
--     EXCEPTION WHEN OTHERS THEN RAISE WARNING '...';
--
-- то есть ЛЮБАЯ ошибка молча проглатывалась. Пользователь появлялся в
-- auth.users, мог войти — но записи в public.users у него не было.
-- В интерфейсе это «пустой профиль» без внятного объяснения, и сам
-- пользователь исправить ничего не может: повторно зарегистрироваться
-- с тем же адресом уже нельзя.
--
-- ЧТО ИМЕННО ПАДАЛО (проверено на боевой базе, в транзакции с откатом)
-- --------------------------------------------------------------------
-- Сценарий А — регистрация без email (вход по телефону или через внешнего
--   провайдера). Колонка public.users.email объявлена NOT NULL, вставка
--   падала. Результат теста на старой версии: «учётка создана, профиль
--   ОТСУТСТВУЕТ».
--
-- Сценарий Б — слишком длинное имя. Сейчас длина не ограничена, но пункт
--   3.3 аудита предполагает добавить CHECK на длину. С таким ограничением
--   вставка падала бы. Тест с имитацией будущего ограничения на старой
--   версии дал тот же результат: «учётка создана, профиль ОТСУТСТВУЕТ».
--
-- Сценарий В — пустые метаданные: full_name подставлялся как '', и с
--   будущим CHECK (length BETWEEN 1 AND 100) это тоже не прошло бы.
--
-- Проверялся и конфликт по UNIQUE (email) — он оказался невозможен:
-- в auth.users есть собственный уникальный индекс по email, второго
-- пользователя с тем же адресом Supabase просто не создаст.
--
-- РЕШЕНИЕ
-- -------
-- 1. Убрана слепая глушилка WHEN OTHERS. Теперь неожиданная ошибка
--    прервёт регистрацию честно: пользователь увидит сообщение и сможет
--    повторить попытку. Это лучше, чем тихо созданная нерабочая учётка,
--    из которой нет выхода.
-- 2. Данные приводятся к безопасному виду ДО вставки, чтобы падать было
--    просто не на чем:
--      • email — если пустой, подставляется технический <id>@no-email.local;
--      • full_name — обрезается до 100 символов, пустое заменяется на
--        «Пользователь» (готово к ограничению из пункта 3.3);
--      • phone — обрезается до 32 символов;
--      • telegram и whatsapp — обрезаются до 64, пустые сохраняются как NULL;
--      • role — как и раньше, всё кроме passenger/driver превращается
--        в passenger.
-- 3. Отдельно обрабатывается unique_violation: если профиль уже создан
--    (например, клиентской страховкой из Auth.tsx), это не ошибка —
--    пишем предупреждение в журнал и продолжаем.
--    Штатная защита ON CONFLICT (id) DO NOTHING тоже сохранена.
--
-- СВЯЗЬ С ДРУГИМИ ПРАВКАМИ
-- ------------------------
-- В тот же день Auth.tsx переведён с upsert на insert (см. миграцию
-- 20260810_fix_1_2_users_update_grants.sql). Клиентская страховка теперь
-- срабатывает только если профиля нет, а если он есть — возвращает ошибку
-- дубликата ключа, которая проглатывается на клиенте. Оба пути согласованы.
--
-- ПРОВЕРЕНО ПОСЛЕ ПРАВКИ (в транзакции с откатом)
-- -----------------------------------------------
--   регистрация без email      → профиль есть, email = <id>@no-email.local
--   имя длиной 300 символов    → профиль есть, имя обрезано до 100
--   пустые метаданные          → профиль есть, имя «Пользователь», роль passenger
--   обычная регистрация        → профиль есть, все поля на месте
--
-- ОТКАТ
-- -----
-- Вернуть прежнее тело функции с блоком EXCEPTION WHEN OTHERS
-- (делать не следует — именно он и прятал проблему).
--
-- Миграция идемпотентна: create or replace.
-- ============================================================

begin;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
DECLARE
  v_role  text;
  v_name  text;
  v_email text;
  v_phone text;
BEGIN
  -- Роль: всё непонятное считаем пассажиром.
  v_role := NEW.raw_user_meta_data->>'role';
  IF v_role IS NULL OR v_role NOT IN ('passenger','driver') THEN
    v_role := 'passenger';
  END IF;

  -- Имя: обрезаем до 100 символов, пустое заменяем.
  v_name := left(trim(coalesce(NEW.raw_user_meta_data->>'full_name','')), 100);
  IF v_name = '' THEN
    v_name := 'Пользователь';
  END IF;

  -- Email: колонка NOT NULL, а при входе по телефону его может не быть.
  v_email := coalesce(NEW.email, NEW.id::text || '@no-email.local');

  v_phone := left(trim(coalesce(NEW.raw_user_meta_data->>'phone','')), 32);

  INSERT INTO public.users (id, email, full_name, phone, role, telegram, whatsapp)
  VALUES (
    NEW.id,
    v_email,
    v_name,
    v_phone,
    v_role,
    left(nullif(trim(coalesce(NEW.raw_user_meta_data->>'telegram','')), ''), 64),
    left(nullif(trim(coalesce(NEW.raw_user_meta_data->>'whatsapp','')), ''), 64)
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;

EXCEPTION
  -- Профиль уже создан (например, страховкой на клиенте) — это не ошибка.
  -- Все остальные ошибки намеренно НЕ перехватываются: пусть регистрация
  -- честно прервётся, а не создаст учётку без профиля.
  WHEN unique_violation THEN
    RAISE WARNING 'handle_new_user: профиль для % уже существует (%)', NEW.id, SQLERRM;
    RETURN NEW;
END;
$function$;

commit;
