-- 20260810_fix_2_5_remove_duplicate_cron.sql
--
-- Закрывает пункт 2.5 аудита AUDIT_2026-08-10.md:
-- «Дублирующиеся cron-задачи закрывают аукционы дважды в минуту».
--
-- ПРОБЛЕМА
-- --------
-- Каждую минуту запускались ДВЕ задачи, делающие ровно одно и то же:
--
--   jobid 1  auto-close-expired-auctions   * * * * *  SELECT close_expired_auctions()
--   jobid 3  auto-finish-expired-auctions  * * * * *  SELECT process_expired_auctions()
--
-- Тела обеих функций совпадают дословно — сверка нормализованных исходников
-- показала расхождение ровно в одном символе регистра: NOW() против now().
-- Обе перебирают истёкшие активные аукционы и вызывают finish_auction.
--
-- Масштаб по журналу cron.job_run_details на момент правки:
--   задача 1 — 126 845 запусков с 14.05.2026
--   задача 3 — 115 191 запуск  с 22.05.2026
--   и ВСЕ 115 191 запуск задачи 3 пришлись ровно на ту же минуту, что и
--   задача 1. То есть это стопроцентный дубль, а не подстраховка.
--
-- ОТКУДА ВЗЯЛОСЬ
-- --------------
-- Задача 1 существовала с 14 мая. Миграция 20260522_fix_cron_jobs.sql от
-- 22 мая создала функцию process_expired_auctions и поставила её в расписание,
-- не проверив, что такая задача уже есть. Обе остались работать.
--
-- ЧЕМ ПЛОХО
-- ---------
-- Два параллельных пути к одной операции — это риск гонки и дублей уведомлений
-- при росте нагрузки. Спасала только блокировка FOR UPDATE внутри
-- finish_auction и проверка статуса. Плюс лишние 1440 запусков в сутки на
-- пустом месте — перед переездом на арендованный VDS это уже не бесплатно.
--
-- РЕШЕНИЕ
-- -------
-- Снять с расписания задачу-дубль и удалить функцию, которую она вызывала.
-- Оставлена более старая задача auto-close-expired-auctions.
-- Проверено: process_expired_auctions не вызывается ни из фронтенда, ни из
-- других функций базы; права на неё были только у postgres и service_role.
--
-- ВАЖНО: СНЯТИЕ ПО ИМЕНИ, А НЕ ПО НОМЕРУ
-- --------------------------------------
-- Патч 8.7 в аудите предлагал `SELECT cron.unschedule(3)`. Здесь используется
-- снятие по имени задачи. Причина: номера задач выдаются последовательно и на
-- новом сервере будут другими. При переносе на VDS задачи создаются заново
-- (см. MOVING_CHECKLIST.md), и номер 3 там может принадлежать чему угодно —
-- вплоть до удаления нужной задачи. Имя же переносится как есть.
--
-- ПОСЛЕ ПЕРЕЕЗДА НА VDS
-- ---------------------
-- Задачу auto-finish-expired-auctions воссоздавать НЕ НУЖНО. Достаточно
-- четырёх: auto-close-expired-auctions (ежеминутно),
-- auto-complete-expired-rides (ежечасно), retention-cleanup (ежедневно в 3:00),
-- cleanup-unpaid-drafts (ежечасно в :07).
--
-- ОТКАТ
-- -----
--   SELECT cron.schedule('auto-finish-expired-auctions', '* * * * *',
--                        'SELECT close_expired_auctions()');
-- (делать не нужно — задача полностью дублирует существующую)
--
-- ПРОВЕРЕНО НА БОЕВОЙ БАЗЕ (в транзакции с откатом)
-- -------------------------------------------------
--   после отключения осталось 4 задачи;
--   close_expired_auctions отработала: истёкший аукцион перешёл в booked,
--   победитель назначен, разослано 2 уведомления;
--   остальные три задачи отработали без ошибок.
--
-- Миграция идемпотентна: снятие задачи обёрнуто в проверку существования.
-- ============================================================

begin;

-- 1) Снять дубль с расписания (по имени, а не по номеру).
do $$
begin
  if exists (select 1 from cron.job where jobname = 'auto-finish-expired-auctions') then
    perform cron.unschedule('auto-finish-expired-auctions');
  end if;
end $$;

-- 2) Удалить функцию, которую вызывала только эта задача.
drop function if exists public.process_expired_auctions();

commit;
