-- Закрывает пункт 2.3 аудита AUDIT_2026-08-10.md:
-- «Ставку можно записать напрямую в таблицу, минуя все проверки».
--
-- ПРОБЛЕМА
-- --------
-- Ролям anon и authenticated был выдан GRANT INSERT на таблицу bids, а
-- политика bids_insert_auth проверяла ровно одно — что bidder_id совпадает
-- с auth.uid(). То есть прямой INSERT в bids обходил ВСЕ правила place_bid:
-- шаг ставки, направление торга (выше/ниже в зависимости от типа поездки),
-- «нельзя ставить на свою поездку», «нельзя две ставки подряд», окончание
-- аукциона.
--
-- Сама по себе такая ставка не двигает current_price — это делает только
-- RPC. Но она попадает в список ставок (bids_select_all разрешает читать
-- всем) и участвует в определении победителя: finish_auction и
-- close_auction_early берут ПОСЛЕДНЮЮ ПО ВРЕМЕНИ ставку. То есть вставил
-- фиктивную ставку последней — выиграл аукцион.
--
-- Подтверждено тестом на боевой базе (в транзакции с откатом): при живой
-- честной ставке 1100 ₽ прямая вставка ставки в 1 ₽ прошла успешно и стала
-- последней в списке.
--
-- СВЕРХ ПУНКТА АУДИТА
-- -------------------
-- У обеих ролей висел ещё и GRANT UPDATE на все колонки bids, включая
-- amount, bidder_id и created_at. Политики UPDATE на таблице нет, поэтому
-- RLS такие запросы и так отсекала — но защита держалась на одной этой
-- настройке. А правка created_at это прямой способ переставить чужую ставку
-- «в конец» очереди и снова стать победителем. Грант отозван, чтобы не
-- зависеть от отсутствия политики.
--
-- РЕШЕНИЕ
-- -------
-- Отозвать INSERT и UPDATE у клиентских ролей. Ставки создаются только через
-- place_bid и accept_current_price — обе SECURITY DEFINER с владельцем
-- postgres, поэтому отзыв клиентских грантов их не затрагивает.
-- Проверено по коду: фронтенд обращается к bids только на чтение
-- (useUnreadCount.ts, Messages.tsx, MyTrips.tsx, TripDetail.tsx —
-- везде .select()), ни одной прямой вставки нет.
--
-- SELECT намеренно оставлен без изменений: список ставок публичный, на нём
-- построена страница поездки.
--
-- ОТЛИЧИЕ ОТ ПАТЧА 8.5 В АУДИТЕ
-- -----------------------------
-- Патч предлагал заодно удалить политику bids_insert_auth. Она здесь
-- намеренно СОХРАНЕНА. Без гранта политика не срабатывает, но если грант
-- когда-нибудь выдадут заново — она хотя бы не даст записать ставку от
-- чужого имени. Такая регрессия в проекте уже случалась: политику
-- rides_update_own удалили в мае и вернули в июне вместе с дырой.
-- Пустая таблица прав важнее аккуратности каталога.
--
-- ОТКАТ
-- -----
--   GRANT INSERT, UPDATE ON public.bids TO authenticated;
-- (делать не следует)
--
-- Миграция идемпотентна.
-- ============================================================

begin;

-- Ставки — только через place_bid и accept_current_price.
revoke insert, update on public.bids from anon, authenticated;

-- SELECT не трогаем: список ставок публичный.
-- Политику bids_insert_auth не удаляем — см. пояснение выше.

commit;
