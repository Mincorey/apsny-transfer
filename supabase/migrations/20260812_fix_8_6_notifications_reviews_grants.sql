-- ============================================================
-- 1. REVIEWS — настоящая дыра, подтверждена тестом
-- ============================================================
--
-- Ролям anon и authenticated был выдан GRANT INSERT на все колонки
-- reviews, а политика reviews_insert_auth проверяла ровно одно — что
-- reviewer_id совпадает с auth.uid(). Прямой INSERT обходил ВСЕ проверки
-- submit_review:
--   * «поездка ещё не завершена» (status = 'completed');
--   * «оценить водителя может только пассажир ЭТОЙ поездки»;
--   * «оценить можно только водителя поездки» (target = водитель).
--
-- Подтверждено на боевой базе 12.08.2026 (в транзакции с откатом):
-- вставка отзыва от лица пользователя A в адрес пользователя B на
-- поездку, в которой A не участвовал, прошла успешно.
--
-- Что именно ломается. Отзывы читают все (reviews_select_all USING true),
-- они выводятся на странице профиля — то есть подложный текст сразу виден
-- посетителям. На users.rating прямая вставка НЕ влияет: триггеров на
-- reviews нет, рейтинг пересчитывает только submit_review. Но пересчитывает
-- он его как AVG(rating) по ВСЕМ отзывам о человеке — поэтому следующий же
-- честный отзыв втягивает подложные единицы в средний балл. Эффект
-- отложенный, оттого и незаметный.
--
-- Ограничение reviews_rating_check (1..5) и UNIQUE (ride_id, reviewer_id)
-- сужают ущерб: оценку вне диапазона не вписать, на одну поездку —
-- не больше одного отзыва от одного человека. Но поездок в ленте много.
--
-- Лечение: отозвать INSERT — отзывы только через submit_review.
REVOKE INSERT ON public.reviews FROM anon, authenticated;

-- UPDATE был выдан на все колонки, включая rating и comment. Политики
-- UPDATE на таблице нет, поэтому RLS такие запросы и так отсекала — но
-- защита держалась на одной этой настройке. Отзываем и его.
REVOKE UPDATE ON public.reviews FROM anon, authenticated;

-- Политику reviews_insert_auth намеренно НЕ удаляем (в отличие от буквы
-- патча 8.6). Без гранта она не срабатывает, но если грант когда-нибудь
-- выдадут заново, она не даст вставить отзыв от чужого имени. Регрессия
-- ровно такого рода в проекте уже случалась: политику rides_update_own
-- удалили в мае и вернули в июне.

-- ============================================================
-- 2. NOTIFICATIONS — гигиена прав, не дыра
-- ============================================================
--
-- ЧЕСТНАЯ ОГОВОРКА. Первоначально предполагалось, что тут дыра: политика
-- notif_update_own имеет USING, но не имеет WITH CHECK, и напрашивается
-- вывод, что пользователь может переписать user_id своего уведомления на
-- чужой — то есть подбросить жертве поддельное «Вы выиграли, переведите
-- предоплату». Проверка на боевой базе это НЕ подтвердила: Postgres для
-- UPDATE при отсутствии WITH CHECK подставляет выражение USING, и попытка
-- увести строку на чужой uid падает с «new row violates row-level security
-- policy». Дыры нет.
--
-- Что оставалось на деле: GRANT UPDATE выдан на все колонки, поэтому
-- пользователь мог переписать title/body/type СВОЕГО уведомления. Видит
-- их только он сам, ущерба нет. Это гигиена прав, а не уязвимость.
-- Приводим права в соответствие с тем, что реально делает интерфейс:
-- MainLayout.tsx помечает уведомления прочитанными и ничего больше.
REVOKE UPDATE ON public.notifications FROM anon, authenticated;
GRANT  UPDATE (is_read) ON public.notifications TO authenticated;

-- INSERT: политика notif_insert_none имеет WITH CHECK false, то есть
-- запрещает вставку всем. Грант при этом висел — снова единственный рубеж
-- вместо двух. Уведомления создают только SECURITY DEFINER функции
-- (place_bid, submit_review, cancel_ride, finish_auction и т. д.), права
-- вызывающего им не нужны.
REVOKE INSERT ON public.notifications FROM anon, authenticated;

-- SELECT анониму: политика notif_select_own сравнивает с auth.uid(),
-- у анонима он NULL, поэтому строк он и так не видит. Убираем грант.
REVOKE SELECT ON public.notifications FROM anon;

-- Явный WITH CHECK в политике. Сейчас он избыточен — Postgres подставляет
-- USING. Пишем его явно, чтобы намерение было видно в коде политики: если
-- когда-нибудь USING расширят (например, до «участник поездки»), без явного
-- WITH CHECK это молча откроет запись в чужие строки.
DROP POLICY IF EXISTS notif_update_own ON public.notifications;
CREATE POLICY notif_update_own ON public.notifications
  FOR UPDATE TO authenticated
  USING      ((SELECT auth.uid()) = user_id)
  WITH CHECK ((SELECT auth.uid()) = user_id);

