-- ПРОБЛЕМА
-- --------
-- Триггерная функция sync_trips_count() была создана 10.08.2026 миграцией
-- 20260810_fix_3_2_trips_count_single_source.sql — то есть в ту же сессию,
-- в которую закрывался пункт 3.7. Патч 3.7 прошёл по списку функций,
-- существовавших на момент аудита, и эту не увидел: её тогда ещё не было.
--
-- В результате она осталась единственной триггерной функцией проекта,
-- открытой на прямой вызов с клиента. Остальные шесть (handle_new_user,
-- force_ride_draft, enforce_vehicle_limit, enforce_single_active_vehicle,
-- notify_contact_telegram, enforce_contact_rate_limit) имеют права
-- {postgres, service_role}, а sync_trips_count — {PUBLIC, anon,
-- authenticated, postgres, service_role}.
--
-- Линтер Supabase выдал по ней сразу два предупреждения:
-- anon_security_definer_function_executable и
-- authenticated_security_definer_function_executable.
--
-- НАСКОЛЬКО ЭТО ОПАСНО НА САМОМ ДЕЛЕ
-- ----------------------------------
-- Прямой вызов /rest/v1/rpc/sync_trips_count упадёт: триггерная функция
-- обращается к записи NEW, которой вне триггера не существует. Накрутить
-- счётчик поездок этим нельзя. То есть это гигиена прав, а не работающая
-- уязвимость — ровно как и было записано в самом пункте 3.7 про
-- publish_ride_free и force_ride_draft. Лишняя поверхность атаки и
-- расхождение с остальными шестью функциями — достаточная причина закрыть.
--
-- Триггеру права вызывающего не нужны: trg_sync_trips_count срабатывает
-- как часть UPDATE таблицы rides, а не как отдельный вызов.
REVOKE ALL ON FUNCTION public.sync_trips_count() FROM PUBLIC, anon, authenticated;

