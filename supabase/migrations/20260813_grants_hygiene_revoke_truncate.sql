-- Гигиена прав по итогам проверки 13.08.2026. Применено к боевой базе.
--
-- ЧТО НАШЛОСЬ. Роли anon и authenticated имели на всех таблицах схемы public
-- права TRUNCATE, TRIGGER, REFERENCES и DELETE. Это не чья-то ошибка: так
-- устроены права по умолчанию в Supabase. Проверено в pg_default_acl — каждая
-- новая таблица в public автоматически получает полный набор привилегий обеим
-- ролям, а разграничение целиком возложено на RLS.
--
-- ПОЧЕМУ ЭТО ВАЖНО. Для DELETE схема работает: политики его блокируют,
-- проверено — удаление возвращает «0 строк». Но на TRUNCATE политики RLS
-- не распространяются вообще, это особенность PostgreSQL. Воспроизведено на
-- стенде с копией боевой схемы: роль authenticated, у которой нет ни одной
-- политики на удаление, командой TRUNCATE снесла все 266 120 ставок.
--
-- Дыры в бою при этом нет: PostgREST команду TRUNCATE не выдаёт, через
-- публичный API до неё не дотянуться. Не хватает последнего рубежа — любая
-- будущая функция с SECURITY INVOKER, инъекция или инструмент, подключившийся
-- анонимным ключом напрямую к SQL, превращают «утекли публичные данные»
-- в «таблицы очищены». Перед переездом на свой сервер это стоит закрыть.
--
-- ЧТО ОСТАВЛЕНО НЕТРОНУТЫМ. Права, которыми приложение пользуется. Отдельно
-- отмечу, что они выданы аккуратнее, чем кажется по таблице целиком: правки
-- выданы по колонкам, а не на таблицу. authenticated может менять в
-- notifications только is_read, а в users — только поля профиля: rating,
-- trips_count, role и email ему недоступны, накрутить рейтинг нельзя.
-- Контакты (phone, telegram, whatsapp, max) не отдаются даже на чтение —
-- ни anon, ни authenticated, они приходят только через get_trip_view после
-- закрытия аукциона. Эта часть сделана правильно и не менялась.

revoke truncate, trigger, references on all tables in schema public from anon, authenticated;
revoke delete on all tables in schema public from anon, authenticated;

-- Единственное удаление, которое делает приложение: своя машина в профиле
-- (Profile.tsx, есть политика vehicles_delete_own).
grant delete on public.vehicles to authenticated;

-- Функция безопасна — фильтрует по текущему пользователю, анониму вернёт
-- пусто, — но выставлять её наружу незачем. Пункт из оценки готовности.
revoke execute on function public.list_paid_ride_ids() from anon;

-- Причина, а не следствие: без этой строки те же права вернутся на первой же
-- созданной таблице.
alter default privileges for role postgres in schema public
  revoke truncate, trigger, references, delete on tables from anon, authenticated;
